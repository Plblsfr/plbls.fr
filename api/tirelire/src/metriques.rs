pub const LARGEUR_PAR_DEFAUT: f64 = 500.0;
pub const LARGEUR_COURIER: f64 = 600.0;

#[derive(Clone, Copy, Debug, PartialEq)]
pub enum Standard {
    Colonne(usize),
    Fixe(f64),
}

pub fn standard(police: &str) -> Standard {
    let nom = police.rsplit('+').next().unwrap_or(police);
    let nom = nom.replace(',', "-");
    let gras = nom.contains("Bold");
    let penche = nom.contains("Italic") || nom.contains("Oblique");
    if nom.starts_with("Helvetica") || nom.starts_with("Arial") {
        Standard::Colonne(usize::from(gras))
    } else if nom.starts_with("Times") {
        Standard::Colonne(2 + usize::from(gras) + 2 * usize::from(penche))
    } else if nom.starts_with("Courier") {
        Standard::Fixe(LARGEUR_COURIER)
    } else {
        Standard::Fixe(LARGEUR_PAR_DEFAUT)
    }
}

pub fn largeur(standard: Standard, c: char) -> f64 {
    match standard {
        Standard::Fixe(l) => l,
        Standard::Colonne(colonne) => GLYPHES
            .binary_search_by_key(&c, |(car, _, _)| *car)
            .ok()
            .and_then(|i| GLYPHES[i].2.get(colonne))
            .map_or(LARGEUR_PAR_DEFAUT, |l| f64::from(*l)),
    }
}

pub fn par_nom(nom: &str) -> Option<char> {
    if let Some(g) = GLYPHES.iter().find(|(_, n, _)| *n == nom) {
        return Some(g.0);
    }
    match nom {
        "space" => Some(' '),
        "hyphen" | "minus" => Some('-'),
        "quoteright" => Some('\u{2019}'),
        "quoteleft" => Some('\u{2018}'),
        _ => nom
            .strip_prefix("uni")
            .filter(|h| h.len() == 4)
            .and_then(|h| u32::from_str_radix(h, 16).ok())
            .and_then(char::from_u32),
    }
}

