#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn table_triee_et_colonnes() {
        assert!(GLYPHES.windows(2).all(|p| p[0].0 < p[1].0));
        assert_eq!(standard("Helvetica"), Standard::Colonne(0));
        assert_eq!(
            standard("ABCDEF+Helvetica-BoldOblique"),
            Standard::Colonne(1)
        );
        assert_eq!(standard("Times-Roman"), Standard::Colonne(2));
        assert_eq!(standard("Times-Bold"), Standard::Colonne(3));
        assert_eq!(standard("Times-Italic"), Standard::Colonne(4));
        assert_eq!(standard("Times-BoldItalic"), Standard::Colonne(5));
        assert_eq!(standard("Courier"), Standard::Fixe(600.0));
        assert_eq!(standard("Inconnue,Bold"), Standard::Fixe(500.0));
        assert_eq!(POLICES[1], "Helvetica-Bold");
    }

    #[test]
    fn largeurs_connues() {
        let helvetica = standard("Helvetica");
        let lues: Vec<f64> = "Aa0, é€".chars().map(|c| largeur(helvetica, c)).collect();
        assert_eq!(lues, [667.0, 556.0, 556.0, 278.0, 278.0, 556.0, 556.0]);
        assert_eq!(largeur(standard("Helvetica-Bold"), 'M'), 833.0);
        assert_eq!(largeur(standard("Times-Roman"), 'M'), 889.0);
        assert_eq!(largeur(helvetica, '\u{4e2d}'), 500.0);
        assert_eq!(largeur(standard("Courier-Bold"), 'i'), 600.0);
    }

    #[test]
    fn noms_de_glyphes_et_win_ansi() {
        assert_eq!(par_nom("eacute"), Some('é'));
        assert_eq!(par_nom("Euro"), Some('€'));
        assert_eq!(par_nom("degree"), Some('°'));
        assert_eq!(par_nom("space"), Some(' '));
        assert_eq!(par_nom("nine"), Some('9'));
        assert_eq!(par_nom("uni00E9"), Some('é'));
        assert_eq!(par_nom("inconnu"), None);
        assert_eq!(win_ansi(0xe9), 'é');
        assert_eq!(win_ansi(0x80), '€');
        assert_eq!(win_ansi(b'A'), 'A');
        assert_eq!(win_ansi(0x81), '\u{fffd}');
        assert_eq!(win_ansi(0x07), '\u{fffd}');
    }
}
