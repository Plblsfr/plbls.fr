test('C6 : rien de public par défaut ; une stat partagée paraît sur le profil puis disparaît ; le profil d’une autre personne montre ce qu’elle partage', async ({ page }) => {
  const srv = await simuler(page, {}, toutVu())
  for (const t of srv.trophees) t.shared = false
  await page.goto('/#/stats/partage')
  await expect(page.getByRole('heading', { name: 'Partage et données', level: 1 })).toBeVisible()
  const reglages = page.getByRole('switch')
  await expect(reglages.first()).toBeVisible()
  for (const r of await reglages.all()) await expect(r).not.toBeChecked()
  await page.getByRole('button', { name: 'Voir mon profil' }).click()
  const profil = page.getByRole('dialog', { name: 'Profil de moi' })
  await expect(profil).toBeVisible()
  await expect.poll(() => srv.appels.filter((a) => a.chemin === '/profiles/me').length).toBe(1)
  await expect(page.locator('[data-bloc="stats-profil"]')).toHaveCount(0)
  await fermerProfil(page)

  await page.getByRole('switch', { name: 'Messages envoyés' }).check()
  await expect.poll(() => srv.appels.filter((a) => a.methode === 'PUT').map((a) => a.corps)).toEqual([{ stats: { 'messaging.messages': true } }])
  await page.getByRole('button', { name: 'Voir mon profil' }).click()
  const bloc = page.locator('[data-bloc="stats-profil"]')
  await expect(bloc).toContainText('Messages envoyés')
  await expect(bloc).toContainText('642')
  await expect(bloc).not.toContainText('Temps actif')
  await bloc.getByRole('button', { name: 'Total' }).click()
  await expect(bloc).toContainText('8 640')
  await bloc.getByRole('button', { name: 'Régler ce que j’affiche' }).click()
  await expect(profil).toHaveCount(0)

  await page.getByRole('switch', { name: 'Messages envoyés' }).uncheck()
  await expect.poll(() => srv.appels.filter((a) => a.methode === 'PUT').at(-1)?.corps).toEqual({ stats: { 'messaging.messages': false } })
  await page.getByRole('button', { name: 'Voir mon profil' }).click()
  await expect(profil).toBeVisible()
  await expect.poll(() => srv.appels.filter((a) => a.chemin === '/profiles/me').length).toBe(3)
  await expect(bloc).toHaveCount(0)
  await fermerProfil(page)

  await page.goto(`/#/s/${SERVEUR}/${SALONS.general}`)
  await expect(page.getByRole('heading', { name: 'général', level: 1 })).toBeVisible()
  const membres = page.getByRole('button', { name: 'Membres', exact: true }).first()
  await expect(membres).toBeVisible()
  if (!(await page.getByTitle('Profil de Camille').isVisible())) await membres.click()
  await page.getByTitle('Profil de Camille').click()
  const camille = page.getByRole('dialog', { name: 'Profil de Camille' })
  await expect(camille.locator('[data-bloc="stats-profil"]')).toContainText('Messages envoyés')
  await expect(camille.locator('[data-bloc="stats-profil"]')).toContainText('77')
  await expect(camille.locator('[data-bloc="stats-profil"]')).toContainText('Pipelette')
  await expect(camille.getByRole('button', { name: 'Régler ce que j’affiche' })).toHaveCount(0)
  expect(srv.appels.some((a) => a.chemin === '/profiles/u-camille')).toBe(true)
})

