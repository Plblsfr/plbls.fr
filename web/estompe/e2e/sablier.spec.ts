const MAINTENANT = new Date('2026-11-18T10:00:00')
const stats = (page: Page) => page.getByRole('link', { name: /^Stats/ })
const annonce = (page: Page) => page.locator('plbls-modal')
const fermerProfil = (page: Page) => page.locator('.pc-back').click({ position: { x: 4, y: 4 } })
const routesLues = (srv: ReturnType<typeof serveurSablier>) => srv.appels.filter((a) => ['/usage', '/entracte', '/sillon', '/messaging'].includes(a.chemin)).map((a) => a.chemin).sort()

function toutVu() {
  const srv = serveurSablier()
  for (const t of srv.trophees) t.seen = true
  for (const r of srv.recaps) r.seen = true
  return srv
}

