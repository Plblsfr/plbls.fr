  await expect(page.getByRole('group', { name: 'Total de la sélection' })).toHaveText(new RegExp(`Opérations\\s*${credits.length}\\s*Débits\\s*0,00\\s€\\s*Crédits\\s*\\+${euros(credits.reduce((n, o) => n + o.amount, 0))}`))
