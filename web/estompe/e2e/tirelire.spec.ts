test('accessibilité : aucune violation axe sur les écrans de la section', async ({ page }) => {
  const { default: AxeBuilder } = await import('@axe-core/playwright')
  await simulerTirelire(page, {}, serveurTirelire(true))
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/#/tirelire/import')
  await page.getByLabel('Relevés PDF à importer').setInputFiles([pdf('releve-2026-11.pdf'), pdf('releve-2026-08-refus.pdf'), pdf('releve-2026-09.pdf')])
  await expect(page.getByRole('heading', { name: '3 fichiers traités' })).toBeVisible()
  const verifier = async (ou: string) => {
    await page.waitForFunction(() => document.getAnimations().every((a) => a.playState !== 'running'))
    const res = await new AxeBuilder({ page }).include('#main').withTags(['wcag2a', 'wcag2aa', 'wcag21a', 'wcag21aa']).analyze()
    expect(res.violations.map((v) => `${ou} · ${v.id} : ${v.nodes.map((n) => `${n.target.join(' ')} ${n.failureSummary}`).join(', ')}`)).toEqual([])
  }
  await verifier('import')
  for (const [chemin, attente] of [['/#/tirelire', 'Pas encore disponible'], ['/#/tirelire/operations', 'Liste des opérations']]) {
    await page.goto(chemin)
    await expect(page.getByRole('region', { name: attente })).toBeVisible()
    await verifier(chemin)
  }
  await page.getByRole('button', { name: 'Afficher les filtres' }).click()
  await verifier('filtres')
  await page.goto('/#/tirelire/operations?from=2026-11-01&q=marche&min=500&direction=debit&type=carte')
  await expect(page.getByRole('list', { name: 'Filtres actifs' }).getByRole('listitem')).toHaveCount(6)
  await verifier('pastilles')
  for (const [chemin, attente] of [['/#/tirelire/a-classer', 'À classer maintenant'], ['/#/tirelire/categories', 'Catégories'], ['/#/tirelire/categories/regles', 'Règles par mots-clés'], ['/#/tirelire/categories/commercants', 'Commerçants']]) {
    await page.goto(chemin)
    await expect(page.getByRole('region', { name: attente, exact: true })).toBeVisible()
    await verifier(chemin)
  }
  await page.getByRole('button', { name: /Marche Colline Villeneuve/ }).click()
  await expect(page.getByText('MARCHE COLLINE VILLENEUVE', { exact: true })).toBeVisible()
  await verifier('commerçant ouvert')
  await page.goto('/#/tirelire/categories/regles')
  await page.getByRole('button', { name: 'Modifier la règle 2' }).click()
  await verifier('règle en modification')
  await page.goto('/#/tirelire/operations')
  await liste(page).getByRole('link').first().click()
  await expect(page.getByRole('region', { name: 'Libellé du relevé' })).toBeVisible()
  await verifier('détail')
})

const libres = (srv: ReturnType<typeof serveurTirelire>) => srv.operations.filter((o) => o.category_id === null).length

test('à classer : bandeau sur l’accueil, règle pour tout le commerçant, annulation, file vidée', async ({ page }) => {
  const srv = await simulerTirelire(page, {}, serveurTirelire(true))
  const depart = libres(srv)
  await page.setViewportSize({ width: 1280, height: 900 })
  await page.goto('/#/tirelire')
  const menu = page.getByRole('navigation', { name: 'Tirelire', exact: true })
  await expect(menu.getByRole('link', { name: /À classer/ })).toContainText(String(depart))
  await page.getByRole('link', { name: new RegExp(`^${depart} opérations à classer`) }).click()
  await expect(page).toHaveURL(/#\/tirelire\/a-classer$/)
  await expect(page.getByRole('heading', { name: 'À classer', level: 1 })).toBeVisible()
  const carte = page.getByRole('region', { name: 'À classer maintenant' })
  const premier = await carte.getByRole('heading', { level: 2 }).innerText()
  const duPremier = srv.operations.filter((o) => o.merchant_name === premier).length
  await expect(carte.getByRole('button', { name: /^Classer/ })).toHaveCount(0)
  await carte.getByRole('button', { name: 'Restaurants', exact: true }).click()
  await carte.getByRole('button', { name: 'Classer en Restaurants' }).click()
  const fait = page.locator('.tir-fait').filter({ hasText: 'Règle créée pour tout le commerçant' })
  await expect(fait).toContainText(`« ${premier} » → Restaurants · ${duPremier} opérations reclassées`)
  await expect(page.getByRole('group', { name: 'Avancement' })).toContainText(`${duPremier} classées sur ${depart}`)
  expect(libres(srv)).toBe(depart - duPremier)
  await expect(carte.getByRole('heading', { level: 2 })).not.toHaveText(premier)
  await fait.getByRole('button', { name: 'Annuler' }).click()
  await expect(fait).toHaveCount(0)
  expect(libres(srv)).toBe(depart)
  await expect(page.getByRole('group', { name: 'Avancement' })).toContainText(`0 classée sur ${depart}`)

  const ensuite = page.getByRole('region', { name: 'Ensuite' })
  await ensuite.getByRole('button', { name: /Streamo Abonnement/ }).click()
  await expect(carte.getByRole('heading', { level: 2 })).toHaveText('Streamo Abonnement')
  await carte.getByRole('button', { name: 'Autres' }).click()
  await carte.getByRole('button', { name: 'Abonnements', exact: true }).click()
  await carte.getByRole('checkbox').uncheck()
  await carte.getByRole('button', { name: 'Classer en Abonnements' }).click()
  await expect(page.locator('.tir-fait').filter({ hasText: 'Opération classée' })).toContainText('cette opération seulement')
  expect(libres(srv)).toBe(depart - 1)

  while (libres(srv) > 0) {
    const avant = libres(srv)
    await carte.getByRole('button', { name: 'Courses', exact: true }).click()
    await carte.getByRole('button', { name: 'Classer en Courses' }).click()
    await expect.poll(() => libres(srv)).toBeLessThan(avant)
    await expect(page.getByRole('group', { name: 'Avancement' })).toContainText(`${depart - libres(srv)} classée`)
  }
  await expect(page.getByRole('heading', { name: 'Tout est classé' })).toBeVisible()
  await expect(menu.getByRole('link', { name: /À classer/ }).locator('.pip')).toHaveCount(0)
  await page.goto('/#/tirelire')
  await expect(page.getByRole('heading', { name: 'Bientôt disponible' })).toBeVisible()
  await expect(page.locator('.tir-bandeau')).toHaveCount(0)
})

